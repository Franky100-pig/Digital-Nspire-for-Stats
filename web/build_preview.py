#!/usr/bin/env python3
"""Bundle the statistics package and the web page into one static folder.

The page runs the *real* ``tinspire_stats`` package -- the same modules the test
suite covers -- inside Pyodide, so this script does nothing clever: it turns the
Python sources into a JavaScript object, drops the bridge and the HTML next to
it, and writes the result to ``web/dist/``.

    python web/build_preview.py                 # build into web/dist
    python web/build_preview.py --serve         # build, then serve on :8000
    python web/build_preview.py --serve 8123    # ...on another port

``web/dist/index.html`` is a normal static page: any web server, a GitHub Pages
branch, or a plain ``python -m http.server`` will do.  It must be served over
HTTP rather than opened as a file, because the browser fetches the Python
runtime from a CDN.
"""

from __future__ import annotations

import argparse
import http.server
import json
import os
import shutil
import socketserver
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent          # .../web
ROOT = HERE.parent                              # project root
PACKAGE = ROOT / "tinspire_stats"
DEFAULT_OUT = HERE / "dist"

#: Files the page needs.  Nothing else from the repository is shipped -- no
#: tests, no tools, no scipy.
BUNDLE = [
    (PACKAGE, "tinspire_stats"),   # source dir            -> virtual path
    (HERE / "engine.py", ""),      # single file, module root
]


def collect() -> dict:
    files: dict[str, str] = {}
    for src, prefix in BUNDLE:
        if src.is_file():
            files[f"{prefix}/{src.name}" if prefix else src.name] = src.read_text(encoding="utf-8")
            continue
        for path in sorted(src.rglob("*.py")):
            rel = path.relative_to(src).as_posix()
            files[f"{prefix}/{rel}"] = path.read_text(encoding="utf-8")
    if not files:
        raise SystemExit(f"nothing to bundle -- looked in {PACKAGE} and {HERE / 'engine.py'}")
    return files


def build(out_dir: Path) -> int:
    files = collect()
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    bundle = out_dir / "core_bundle.js"
    bundle.write_text(
        "// Generated by web/build_preview.py -- do not edit.\n"
        "// The whole tinspire_stats package, plus the browser entry module.\n"
        "window.LA_CORE_FILES = "
        + json.dumps(files, ensure_ascii=False, indent=1)
        + ";\n",
        encoding="utf-8",
    )

    shutil.copy(HERE / "la-bridge.js", out_dir / "la-bridge.js")
    index = (HERE / "index.template.html").read_text(encoding="utf-8")
    index = index.replace("{{ENTRY_MODULE}}", "engine")
    (out_dir / "index.html").write_text(index, encoding="utf-8")

    total = sum(len(v.encode("utf-8")) for v in files.values())
    print(f"built  {out_dir}")
    print(f"  index.html        {len(index.encode('utf-8')):>9,} bytes")
    print(f"  la-bridge.js      {(HERE / 'la-bridge.js').stat().st_size:>9,} bytes")
    print(f"  core_bundle.js    {bundle.stat().st_size:>9,} bytes  "
          f"({len(files)} Python modules, {total:,} bytes of source)")
    return 0


def serve(directory: Path, port: int) -> None:
    class Handler(http.server.SimpleHTTPRequestHandler):
        def __init__(self, *a, **kw):
            super().__init__(*a, directory=str(directory), **kw)

        def log_message(self, fmt, *args):  # keep the console readable
            sys.stderr.write(f"  {self.address_string()} {fmt % args}\n")

    with socketserver.TCPServer(("127.0.0.1", port), Handler) as httpd:
        print(f"serving http://127.0.0.1:{port}/  (Ctrl-C to stop)")
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            print("\nstopped")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output folder")
    ap.add_argument("--serve", nargs="?", const=8000, type=int, metavar="PORT",
                    help="serve the built folder after building")
    args = ap.parse_args(argv)

    rc = build(args.out.resolve())
    if rc == 0 and args.serve:
        serve(args.out.resolve(), args.serve)
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
